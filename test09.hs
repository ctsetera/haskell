import Control.Monad (when)
import Data.Foldable (foldr')

gt :: Int -> Int -> Bool
gt x y = x > y

main :: IO ()
main =
    do
        let numbers = [1 .. 5]

        -- これは、リスト内の5から1にかけて足し合わせる　初期値を(+)の後に設定できる
        -- この場合なら、初期値は0
        -- 展開すると　1 + (2 + (3 + (4 + (5 + 10))))　という具合
        print $ foldr (+) 10 numbers
        -- 省略しないで書くとこう　accは「残りの計算対象」
        print $ foldr (\x acc -> x + acc) 10 numbers

        -- foldlもあるよ
        -- 展開すると　(((((10 + 1) + 2) + 3) + 4) + 5　という具合
        print $ foldl (+) 10 numbers
        -- 省略しないで書くとこう　accは「今までやってきた計算結果」
        print $ foldl (\acc x -> acc + x) 10 numbers

        -- その他、遅延評価をせずに都度計算を行うfoldr'・foldl'もある

        putStrLn ""

        -- \***************************** どう使い分ける？ *****************************
        --
        -- 単純なリスト内の値を使った計算であれば「foldl'」
        -- 理由は、どうせすべての値を使って計算するのであれば遅延評価である必要がないため
        -- foldr'でない理由は、例えば、初期値からリスト内のアイテムを使って引き算をしたいときに計算を解釈する順番的に期待通りにならないため
        print $ foldl' (-) 200 [10, 20, 30, 40]
        print $ foldr' (-) 200 [10, 20, 30, 40]

        putStrLn ""

        -- リストから新しい構造のリストを作りたいときは「foldr」
        -- だたし、「リストから新しい構造のリストを作る」というのはmapでできる（つまりmapの内部実装ではfoldrを使用している）
        -- なぜこのような用途ではfoldrの方が都合が良いか？
        -- foldrで上記を満たしたいとなると、例えば以下のように書ける
        print $ foldr (\x acc -> gt x 5 : acc) [] [1 .. 10]

        -- この場合の「:」は右側に記述したリストの先頭に左に配置した変数を結合したリストを作成する
        -- 一見、foldlでも書けそうだが、Haskellのリストは先頭からしか参照できず、うしろの方を参照するためにはリストに入ったアイテム数のぶんだけオーダーが増えてしまうので
        -- 単にfoldlで書くとパフォーマンスが悪くなってしまう
        -- foldrのaccが「残りの計算結果」であることから、Haskellのリストの仕様とも相まって都合がいい

        -- さらに、foldrであれば、こんな感じで「先頭から要素を取り出す」を実装したとして、
        -- 計算部分でacc（残りの計算対象）を使用しなければaccを考える必要がないとコンパイラは判断するため（遅延評価）、
        -- 無限リストですら扱えてしまう
        --
        print $ foldr (\x acc -> x) 0 [1 ..]

-- 同じく遅延評価のfoldlだが、これは永遠に応答が返ってくることはない
-- 理由は、foldlではaccに入るのが「今までやってきた計算結果」だから、
-- ラムダ式の処理部分でaccを使うような記述にしなくてもaccをなにかしら解釈する必要があるから？
--
-- print $ foldl (\acc x -> x) 0 [1 ..]
